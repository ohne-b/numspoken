export function languageFor(code: LocaleCode): Language {
  return languages.find((language) => language.code === code)!;
}

export function isLocale(value: unknown): value is LocaleCode {
  return typeof value === 'string' && Object.hasOwn(localeLoaders, value);
}

export function formatNumber(value: number, language: Language) {
  return new Intl.NumberFormat(language.formatter, {
    numberingSystem: 'latn',
  }).format(value);
}
